// Writes formcheck/app/default_rules.json: the form check service's built-in fallback copy of the base pack's
// form check rules, norms and critical documents (used only when a /score request carries no rules).
import fs from 'node:fs';
import path from 'node:path';
import { APP_TYPES } from '../src/rules/schema.js';
import { baseRules } from '../src/rules/migrate-from-json.js';

const r = await baseRules();
const out = {
  note: 'Generated by api/scripts/export-formcheck-defaults.ts from the 2026-27 v1 base pack. The API sends the case rules with every /score request; this copy is the fallback.',
  version: r.label,
  formCheckRules: r.formCheckRules,
  norms: r.norms(),
  requiredDocs: Object.fromEntries(APP_TYPES.map((t) => [t, r.criticalKinds(t)])),
};
const file = path.resolve(process.cwd(), '../formcheck/app/default_rules.json');
fs.writeFileSync(file, `${JSON.stringify(out, null, 2)}\n`);
console.log(`Wrote ${file}`);
